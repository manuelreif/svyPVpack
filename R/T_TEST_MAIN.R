#' Computation of a t-test for data from a complex survey design with usage of
#' plausible values
#' 
#' Computes a one-sample or two-sample t-test for data from a complex survey
#' design with usage of plausible values.
#' 
#' All variables mentioned in the formula object must be part of the survey
#' design object.  Instead of the symbols, which were used for numbering the
#' plausible values use '..' as notation (e.g. placeholder = 1:5 and PVLIT..
#' stands for PVLIT1, PVLIT2, PVLIT3, PVLIT4, PVLIT5). Missing values are
#' deleted listwise.
#' 
#' @param formula Formula, outcome~group for two-sample, outcome~0 or outcome~1
#' for one-sample (all variables have to be part of a survey design objecct
#' created by the survey package). For a notation description for the plausible
#' values see in 'details'.
#' @param design a survey design which was generated by the \code{survey}
#' package.
#' @param placeholder a vector of symbols, which were used for numbering the
#' plausible values. For a detailed description see in 'details'.
#' @return The function returns a list, which includes the following three
#' dataframes.
#' 
#' \item{DESC}{Shows mean and SE for each group.} \item{TEST}{Shows the test
#' statistic (t.value, degf and Pr.t).} \item{N}{Shows the unweighted number of
#' cases and the sum of weights (NA's excluded) within each group.}
#' @author Jakob Peterbauer
#' @seealso \code{\link{svyttest}, \link{svyPVpm}, \link{svyPVglm}}
#' @references Lumley, T. (2010). \emph{Complex Surveys}. Hoboken, NJ: Wiley.
#' 
#' Saerndal, C.-E. & Swensson, B. & Wretman, J. (1992). \emph{Model Assisted
#' Survey Sampling}. New York: Springer.
#' 
#' Chaudhuri, A. & Stenger, H. (2005). \emph{Survey Sampling. Theory and
#' Methods}. Boka Raton, FL: Chapman & Hall/CRC. .
#' @keywords ttest
#' @examples
#' 
#' data(svy_example1)
#' res <- svyPVttest(plaus.. ~ sex, svy.exrep, placeholder = 1:3)
#' 
#' res
#' 
#' @export svyPVttest
svyPVttest <- function(formula, 
                       design, 
                       placeholder = 1:10){
  # ERROR MESSAGE "NO PVs"
  if(length(grep("\\.\\.",formula)) == 0){
    stop("NO PVS -> use svyglm in package survey")}
  if(as.character(formula)[3] %in% c("0","1")){
    # prepare model t-test arguments
    as.char.forms <- lapply(placeholder,
                            function(x) 
                              (gsub("\\.\\.", x, formula)))
    char.calls <-  lapply(as.char.forms, 
                          function(x)
                            (paste(x[2],x[1], x[3])))
    formulas <- lapply(char.calls, as.formula)
    # compute test results
    mods <- lapply(lapply(formulas,as.formula), 
                   t.test.aux, 
                   design)
    # get test results & compute end results
    LIST <- lapply(mods, function(x)(x$DESC))
    TAB <- do.call(rbind,LIST)
    DESC.est <- TAB[,1]
    DESC.sds <- TAB[,2]
    DESC.var <- DESC.sds^2
    DESC.M <- mean(DESC.est)
    DESC.sampling.v <- mean(DESC.var)
    DESC.imputation.v <- var(DESC.est) 
    DESC.tot.se <- sqrt(DESC.sampling.v + 
                          ((1+1/length(placeholder)) * 
                             DESC.imputation.v))
    DESC.TAB.END.RES <- data.frame(mean=DESC.M, 
                                   se=DESC.tot.se)
    t.value <- DESC.M/DESC.tot.se  
    t.value.d <- abs(t.value)
    Pr.t <- pt(t.value.d, 
               degf(design), 
               lower.tail = FALSE)*2
    TEST.RES <- data.frame(t.value, 
                           degf(design), 
                           format.pval(Pr.t))
    colnames(TEST.RES) <- c("t.value", "degf", "Pr.t")
    rownames(TEST.RES) <- c("")
    N <- mods[[1]]$N
    FINAL.RES <- list(DESC = DESC.TAB.END.RES, 
                      TEST = TEST.RES, 
                      N=N)
    return(FINAL.RES)
  }
  else{
    # prepare model t-test arguments
    as.char.forms <- lapply(placeholder,
                            function(x) 
                              (gsub("\\.\\.", x, formula)))
    char.calls <-  lapply(as.char.forms, 
                          function(x)
                            (paste(x[2],x[1], x[3])))
    formulas <- lapply(char.calls, as.formula)
    # compute test results
    mods <- lapply(lapply(formulas,as.formula), 
                   t.test.aux, 
                   design)
    DESC.TAB <- lapply(mods, function(x)(x$DESC))
    # get test results & compute end results
    DESC.TAB.4.END.RES <- DESC.TAB[[1]]
    DESC.est <- do.call(rbind, 
                        lapply(DESC.TAB, 
                               function(x)
                                 (t(as.data.frame(x)[,2]))
                        )
    )
    DESC.sds <- do.call(rbind, 
                        lapply(DESC.TAB, 
                               function(x)
                                 (t(as.data.frame(x)[,3]))
                        )
    )
    DESC.var <- DESC.sds^2
    DESC.M <- apply(DESC.est, 2, mean)
    DESC.sampling.v <- apply(DESC.var, 2, mean)
    DESC.imputation.v <- apply(DESC.est, 2, var) 
    DESC.tot.se <- sqrt(DESC.sampling.v + 
                          ((1+1/length(placeholder)) * DESC.imputation.v))
    DESC.TAB.4.END.RES[,2] <- DESC.M
    DESC.TAB.4.END.RES[,3] <- DESC.tot.se
    DESC.TAB.END.RES <- DESC.TAB.4.END.RES
    
    TEST.TAB <- lapply(mods, function(x)(x$TEST))
    TEST.est <- do.call(rbind, 
                        lapply(TEST.TAB, 
                               function(x)
                                 (t(as.data.frame(x)[1,]))
                        )
    )
    TEST.sds <- do.call(rbind, 
                        lapply(TEST.TAB, 
                               function(x)
                                 (t(as.data.frame(x)[2,]))
                        )
    )
    TEST.var <- TEST.sds^2
    TEST.M <- mean(TEST.est)
    TEST.sampling.v <- mean(TEST.var)
    TEST.imputation.v <- var(TEST.est) 
    TEST.tot.se <- sqrt(TEST.sampling.v + 
                          ((1+1/length(placeholder)) * TEST.imputation.v))
    t.value <- TEST.M/TEST.tot.se  
    t.value.d <- abs(t.value)
    Pr.t <- pt(t.value.d, (degf(design)-1), lower.tail = FALSE)*2
    TEST.RES <- data.frame(t.value, (degf(design)-1), format.pval(Pr.t))
    colnames(TEST.RES) <- c("t.value", "degf", "Pr.t")
    rownames(TEST.RES) <- c("")
    N <- mods[[1]]$N
    FINAL.RES <- list(DESC = DESC.TAB.END.RES, 
                      TEST = TEST.RES, 
                      N=N)
    return(FINAL.RES)
  }
}


