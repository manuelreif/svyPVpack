#' Proportion in levels estimation
#' 
#' This function categorizes the plausible values into specific user defined
#' levels, to estimate the proportion of population totals within this levels.
#' 
#' 
#' All variables, including the subsetting ones defined with \code{by}, must be
#' part of the survey design object.
#' 
#' Missing values are deleted listwise.
#' 
#' Note that '.' is not allowed as part of the level string of a \code{by}
#' variable. For example c("1.thing","2.thing") is not allowed and will cause a
#' error message.
#' 
#' @param by A formula statement is expected which splits the data into several
#' subsets.
#' @param svydat A survey design (\code{svydesign} as well as
#' \code{svrepdesign}) which was generated by the \code{survey} package. To
#' figure out how to create a survey design object, please read the help files
#' for the \code{survey} package.
#' @param pvs A character vector which includes the colnames of the plausible
#' values. These variables must be part of the survey design comitted as
#' \code{svydat}.
#' @param CATDEF A numeric vector which contains the cut points with which the
#' plausible values are categorized. The input follows the same notation as the
#' break argument in the \code{cut} function.
#' @param levlab A character vector which contains the levels labels. Default
#' is NA -- which means that the labels will be \code{paste0("level",
#' NUMBEROFLEVELS)}
#' @param right Corresponds to the right argument in the \code{cut} function.
#' If TRUE, which is the default, the intervals built by this function are
#' closed on the right.
#' @param colN If TRUE the colnames will equal the grouping variable names from
#' the by statement. If FALSE, which is the default, the names will be Group1
#' up to Group k.
#' @return The function returns a data.frame with the following columns
#' \item{Group1..k}{The first k-1 columns show the different levels of the k-1
#' subsetting groups, provided with \code{by}. The kth group column contains
#' the different levels defined by the \code{CATDEF} vector.}
#' \item{Number.of.cases}{Shows the unweighted number of cases (NA's excluded)
#' within each group.} \item{Sum.of.weights}{Shows the sum of weights (NA's
#' excluded) within each group.} \item{Proportion}{Contains the estimate of the
#' conditional proportion of persons on each level given the categories of the
#' first k-1 groups.} \item{Proportion.SE}{Contains the SE of the proportion
#' estimate.}
#' @author Manuel Reif
#' @seealso \code{\link{svyPVbenchmark}}
#' @references Lumley, T. (2010). \emph{Complex Surveys}. Hoboken, NJ: Wiley.
#' 
#' Saerndal, C.-E. & Swensson, B. & Wretman, J. (1992). \emph{Model Assisted
#' Survey Sampling}. New York: Springer.
#' 
#' Chaudhuri, A. & Stenger, H. (2005). \emph{Survey Sampling. Theory and
#' Methods}. Boka Raton, FL: Chapman & Hall/CRC.
#' @keywords level
#' @examples
#' 
#' 
#' data(svy_example1)
#' 
#' erg_l <- svyPVlevel(by = ~ sex, svydat=svy.exrep, 
#' pvs=c("plaus1","plaus2","plaus3"), CATDEF=c(0,310,322,400))
#' 
#' erg_l
#' 
#' 
#' 
#' @export svyPVlevel
svyPVlevel <-
#function(by, svydat, pvs, CATDEF=NA, addcountry=TRUE)
function(by, svydat, pvs, CATDEF, levlab=NA, right=TRUE, colN=FALSE)
# CATEDEF = similar to the 'breaks' argument in the cut() function.
##1 so if you want to create level1 between 0 and 100, level2 between 100 and 300 and level3 between 300 and 500 the input has to look like:
## c(0,100,300,500)
  # which creates half opened intervals (0,100] ; (100,300] ; (300,500] which means that the interval is closed on the left an open on the right. so 0 is NOT included in the first interval, but 100 is. 100 is not included in the second interval but 300 is. etc ...
# so it is better to give the following CATDEF statement if you want to create levels like mentioned in ##1
  ## c(-0.1,100,300,501) --> or something similar
## colN --> add colnames
  
{

  
if(any(is.na(levlab)))
{
CATDEFlab <- paste0("level",1:(length(CATDEF)-1))
  
} else {
  
  #if(length(grep("\\.",levlab)) > 0) {"Check levels. No '.' allowed!"}
  
  CATDEFlab  <- levlab
}
  

PVPRS <- svydat$variables[, pvs]


LEVPVs <- data.frame(lapply(PVPRS, function(x) cut(x,CATDEF,CATDEFlab, right=right)))
colnames(LEVPVs) <- paste0(colnames(PVPRS),"_cat")

svydat2 <- 0
addALL <- paste0("svydat2 <- update(svydat, ",paste0(colnames(LEVPVs),"=LEVPVs$",colnames(LEVPVs),collapse=" , "),")")


# create svydat2 which includes the categorized plausible values
eval(parse(text=addALL))  


ergperc <- pv_perc(by=by, svydat=svydat2, pvcat=colnames(LEVPVs))
#ergperc


pm  <- mergeALL(ergperc)


### um die ordnung der factors gleich zu lassen (vor allem wichtig bezogen auf grafiken) wird hier nochmal umgeordnet so wie es im datensatz ?blich ist

mybys <- all.vars(by)
# facordall <- mapply(function(x,number) factor(pm[,number], levels=levels(svydat2$variables[[x]])), x=mybys, number=1:length(mybys),SIMPLIFY=FALSE)
# 
# facordallDF <- data.frame(facordall)

facordallDF <- fALL(mybys,pm, svydat)


pm[,1:length(mybys)] <- facordallDF 

# Beschriftung
if(colN)
{
colnames(pm)[1:(length(mybys)+1)] <- c(mybys,"levels") 

}

# if(addcountry)
# {  
#   pm  <- data.frame("Country"=unique(svydat$variables$CNTRYID), pm) 
# }

return(pm)  
  
}
