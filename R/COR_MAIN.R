#' Survey-weighted Correlation Estimation with uasge of palusible values.
#' 
#' svyPVcor estimates the Pearson product-moment correlation coefficient and
#' its standard error for data from a complex survey design with plausible
#' values.
#' 
#' All variables mentioned in the formula object must be part of the survey
#' design object. Instead of the symbols, which were used for numbering the
#' plausible values use '..' as notation (e.g. placeholder = 1:5 and PVLIT..
#' stands for PVLIT1, PVLIT2, PVLIT3, PVLIT4, PVLIT5).Missing values are
#' deleted listwise.
#' 
#' @param formula Formula, x~y for the correlation between x and y (both
#' variables have to be part of a survey design objecct created by the
#' \code{survey} package). For a notation description for the plausible values
#' see in 'details'.
#' @param design A survey design which was generated by the \code{survey}
#' package .
#' @param placeholder A vector of symbols, which were used for numbering of the
#' plausible values. For a detailed description see in 'details'.
#' @return The function returns a data.frame with the following columns
#' \item{COR}{Shows the Pearson product-moment correlation coefficient between
#' x and y.} \item{SE}{Shows the SE for the Pearson product-moment correlation
#' between x and y.} \item{Number.of.cases}{Shows the unweighted number of
#' cases (NA's excluded) within each group.} \item{Sum.of.weights}{Shows the
#' sum of weights (NA's excluded) within each group.}
#' @author Jakob Peterbauer
#' @seealso \code{\link{cov.wt}}, \code{\link{svyPVeta}}
#' @references Lumley, T. (2010). \emph{Complex Surveys}. Hoboken, NJ: Wiley.
#' 
#' Saerndal, C.-E. & Swensson, B. & Wretman, J. (1992). \emph{Model Assisted
#' Survey Sampling}. New York: Springer.
#' 
#' Chaudhuri, A. & Stenger, H. (2005). \emph{Survey Sampling. Theory and
#' Methods}. Boka Raton, FL: Chapman & Hall/CRC.
#' @keywords correlation
#' @examples
#' 
#' # data(svy_example1)
#' 
#' @export svyPVcor
svyPVcor <- function(formula, 
                     design, 
                     placeholder = 1:10){
  # prepare args
  x.name <- as.character(formula)[2]
  y.name <- as.character(formula)[3] 
  if(length(grep("\\.\\.", x.name))==1){
    x.name  <- lapply(placeholder,
                      function(x) gsub("\\.\\.", x, x.name))
  }
  if(length(grep("\\.\\.", y.name))==1){
    y.name  <- lapply(placeholder,
                      function(x) gsub("\\.\\.", x, y.name))
  }
  x.name.4.df <- unlist(x.name)
  y.name.4.df <- unlist(y.name)
  Y <- as.data.frame(design$variables[y.name.4.df])
  X <- as.data.frame(design$variables[x.name.4.df])
  # create NA-dummy to count cases/weights & for survey update
  NA.dummy.matrix <- cbind(X,Y)
  NA.dummy <- apply(NA.dummy.matrix, 
                    1, 
                    function(x){
                      any(is.na(x))}
  )
  n <- sum(design$pweights[NA.dummy==FALSE])
  N <- sum(NA.dummy==FALSE)
  updated.design <- update(design, NA.dummy = NA.dummy)
  # computation with two vectors as input
  if(max(dim(as.matrix(X))[2],
         dim(as.matrix(Y))[2]) == 1){
    result <- cor.aux.func(X[NA.dummy == FALSE,], 
                           Y[NA.dummy == FALSE,], 
                           subset(updated.design, 
                                  NA.dummy == FALSE)
    )  
    finalres <- rbind(t(as.data.frame(result)), N, n) 
    rownames(finalres) <- c("COR", "SE", "number.of.cases",
                            "sum.of.weights")
    t(finalres)
  }
  else{
    # computation with one vectors and one matrix as input
    if(dim(as.matrix(X))[2] == 1 &
         dim(as.matrix(Y))[2] > 1){
      X.d <- matrix(data = unlist(rep(X, dim(as.matrix(Y))[2])), 
                    ncol = dim(as.matrix(Y))[2])  
      PVs.d <- lapply(1:dim(as.matrix(X.d))[2], 
                      function(n){
                        inp1 <- X.d[NA.dummy == FALSE,n]
                        inp2 <- Y[NA.dummy == FALSE,n]
                        cor.aux.func(inp1, 
                                     inp2, 
                                     subset(updated.design, 
                                            NA.dummy == FALSE))}
      )
    }  
    if(dim(as.matrix(X))[2] > 1 &
         dim(as.matrix(Y))[2] == 1){
      Y.d <- matrix(data = unlist(rep(Y, dim(as.matrix(X))[2])), 
                    ncol = dim(as.matrix(X))[2])  
      PVs.d <- lapply(1:dim(as.matrix(Y.d))[2], 
                      function(n){
                        inp1 <- X[NA.dummy == FALSE,n]
                        inp2 <- Y.d[NA.dummy == FALSE,n]
                        cor.aux.func(inp1, 
                                     inp2, 
                                     subset(updated.design, 
                                            NA.dummy == FALSE))}
      )
    }  
    # computation with two matrices as input
    if(dim(as.matrix(X))[2] > 1 &
         dim(as.matrix(Y))[2] > 1){
      PVs.d <- lapply(1:dim(as.matrix(X))[2], function(n){
        inp1 <- X[NA.dummy == FALSE,n]
        inp2 <- Y[NA.dummy == FALSE,n]
        cor.aux.func(inp1, inp2, subset(updated.design, 
                                        NA.dummy == FALSE))}
      ) 
    }
    # dataframe with coefficients
    unlPV.with.lab <- as.data.frame(PVs.d)
    # point estimators + SD
    ndummy1 <- seq(1,2*max(dim(as.matrix(X))[2], 
                           dim(as.matrix(Y))[2]),2)
    ndummy2 <- 1+seq(1,2*max(dim(as.matrix(X))[2],
                             dim(as.matrix(Y))[2]),2)
    PV.means <- unlist(unlPV.with.lab[ndummy1])
    PV.ses.d <- unlist(unlPV.with.lab[ndummy2])
    PV.ses <- PV.ses.d^2
    Means <- mean(PV.means)
    sampling.v <- mean(PV.ses)
    imputation.v <- var(PV.means) 
    tot.v <- sqrt(sampling.v + ((1+1/length(placeholder)) * 
                                  imputation.v))
    # compilation of final result object
    result <- rbind(Means,tot.v,N,n)
    rownames(result) <- c("COR", "SE", "number.of.cases",
                          "sum.of.weights")
    # return final result object
    t(result)
  }
}
